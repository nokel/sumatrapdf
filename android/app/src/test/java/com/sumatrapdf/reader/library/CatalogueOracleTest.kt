package com.sumatrapdf.reader.library

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.BeforeClass
import org.junit.Test
import java.io.File

// The genre, series-grouping and catalogue ports are checked against the
// Python they came from, run over the reader's own 187-book library.
//
// library_real.json is the desktop's own audiobook/cache/library/library.json
// and partitions_real.json its partitions.json; catalogue_oracle.json is what
// audiobook/library/{genre,learn,shelf}.py produce from them, generated by
// scratchpad/catalogue_oracle.py with only fitz, pdfbook and the lore store
// stubbed out.
//
// learn.py's second grouping pass uses scikit-learn, which the Kotlin port
// replaces with its own TF-IDF and average-linkage clustering. The
// seriesGrouping test is the measurement of that replacement: it fails with
// the exact rows that differ rather than asserting they cannot.
class CatalogueOracleTest {

    companion object {
        private lateinit var oracle: JSONObject
        private lateinit var roots: List<String>
        private lateinit var source: LibraryIndex

        @BeforeClass
        @JvmStatic
        fun setUp() {
            val root = File(System.getProperty("java.io.tmpdir"), "sumatra-oracle-${System.nanoTime()}")
            File(root, "library").mkdirs()
            LibraryCache.root = File(root, "library")

            oracle = JSONObject(resource("catalogue_oracle.json"))
            source = indexFromJson(resource("library_real.json"))!!
            roots = oracle.optJSONArray("roots")!!.let { arr ->
                (0 until arr.length()).map { arr.getString(it) }
            }

            // genre.py reads the subjects the online lookup cached; the same
            // files are laid down here so both sides see the same input.
            val meta = LibraryCache.dir("meta")
            val subjects = oracle.getJSONObject("subjects")
            for (id in subjects.keys()) {
                val o = JSONObject()
                o.put("subjects", subjects.getJSONArray(id))
                File(meta, "$id.json").writeText(o.toString())
            }
            File(LibraryCache.root, PARTITION_STORE_FILE)
                .writeText(resource("partitions_real.json"))
        }

        private fun resource(name: String): String =
            CatalogueOracleTest::class.java.classLoader!!
                .getResourceAsStream(name)!!.bufferedReader().readText()

        private fun books(): MutableList<Book> =
            indexFromJson(resource("library_real.json"))!!.books.toMutableList()
    }

    @Test
    fun theOracleIsTheRealLibrary() {
        assertEquals(187, source.books.size)
        assertEquals(187, oracle.getInt("books"))
        assertEquals(187, oracle.getJSONObject("subjects").length())
        assertEquals(39, oracle.getJSONArray("rows").length())
        assertTrue(roots.isNotEmpty())
        assertTrue(loadPartitions().partitions.isNotEmpty())
        assertTrue(cachedSubjects(source.books.first().id) != null)
    }

    @Test
    fun genreMatchesThePythonOnEveryBook() {
        val mine = books()
        assignGenres(mine)
        val want = oracle.getJSONObject("genres")
        val misses = mutableListOf<String>()
        for (b in mine) {
            val row = want.getJSONObject(b.id)
            val genre = row.optString("genre", "").takeIf { it.isNotBlank() }
            val sub = if (row.isNull("subgenre")) null else row.optString("subgenre")
            if (b.genre != genre || b.subgenre != sub) {
                misses += "${b.title}: want $genre/$sub got ${b.genre}/${b.subgenre}"
            }
        }
        assertTrue(
            "${misses.size} of ${mine.size} books are shelved differently:\n" +
                misses.take(20).joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun seriesGroupingMatchesThePython() {
        val mine = books()
        val (found, _) = seriesGroups(mine, mine)
        val want = oracle.getJSONArray("groups")
        val wantByName = LinkedHashMap<String, Set<String>>()
        for (i in 0 until want.length()) {
            val g = want.getJSONObject(i)
            val ids = g.getJSONArray("ids")
            wantByName[g.getString("name")] = (0 until ids.length()).map { ids.getString(it) }.toSet()
        }
        val gotByName = found.associate { (name, members) -> name to members.map { it.id }.toSet() }

        val misses = mutableListOf<String>()
        for ((name, ids) in wantByName) {
            val got = gotByName[name]
            if (got == null) {
                misses += "missing group '$name' (${ids.size} books)"
            } else if (got != ids) {
                misses += "group '$name': want ${ids.size} books, got ${got.size}"
            }
        }
        for (name in gotByName.keys) {
            if (name !in wantByName) misses += "extra group '$name'"
        }
        assertTrue(
            "series grouping differs on ${misses.size} of ${wantByName.size} groups:\n" +
                misses.take(20).joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun catalogueRowsMatchThePython() {
        val mine = books()
        val catalogue = buildCatalogue(mine, roots)
        val want = oracle.getJSONArray("rows")
        val wantRows = LinkedHashMap<String, JSONObject>()
        for (i in 0 until want.length()) {
            val o = want.getJSONObject(i)
            wantRows[o.getString("key")] = o
        }
        val gotRows = catalogue.rows.associateBy { it.key }

        val misses = mutableListOf<String>()
        for ((key, o) in wantRows) {
            val row = gotRows[key]
            if (row == null) {
                misses += "missing row $key (${o.getString("name")})"
                continue
            }
            fun check(field: String, want: Any?, got: Any?) {
                if (want != got) misses += "$key.$field: want $want got $got"
            }
            check("name", o.getString("name"), row.name)
            check("kind", o.getString("kind"), row.kind)
            check("parent", if (o.isNull("parent")) null else o.getString("parent"), row.parent)
            check("depth", o.getInt("depth"), row.depth)
            check("books", o.getInt("books"), row.books)
            check("direct", o.getInt("direct"), row.direct)
            check("booknlp", o.getInt("booknlp"), row.booknlp)
            check("pages", o.getInt("pages"), row.pages)
            check("author", if (o.isNull("author")) null else o.getString("author"), row.author)
            check("genre", o.getString("genre"), row.genre)
            check("subgenre", if (o.isNull("subgenre")) null else o.getString("subgenre"), row.subgenre)
            check("guessed", if (o.isNull("guessed")) null else o.getString("guessed"), row.guessed)
            val chain = o.getJSONArray("chain").let { a -> (0 until a.length()).map { a.getString(it) } }
            check("chain", chain, row.chain)
        }
        for (key in gotRows.keys) {
            if (key !in wantRows) misses += "extra row $key"
        }
        assertTrue(
            "${misses.size} catalogue differences over ${wantRows.size} rows:\n" +
                misses.take(30).joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun everyBookLandsInThePythonsSeriesAndGenre() {
        val mine = books()
        buildCatalogue(mine, roots)
        val want = oracle.getJSONObject("book_rows")
        val misses = mutableListOf<String>()
        for (b in mine) {
            val o = want.getJSONObject(b.id)
            val series = if (o.isNull("series")) null else o.getString("series")
            val key = if (o.isNull("series_key")) null else o.getString("series_key")
            val keys = o.getJSONArray("series_keys").let { a -> (0 until a.length()).map { a.getString(it) } }
            val genre = if (o.isNull("genre")) null else o.getString("genre")
            if (b.series != series || b.seriesKey != key || b.seriesKeys != keys || b.genre != genre) {
                misses += "${b.title}: want $series/$key/$genre got ${b.series}/${b.seriesKey}/${b.genre}"
            }
        }
        assertTrue(
            "${misses.size} of ${mine.size} books differ:\n" + misses.take(20).joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun theBookOrderMatchesThePython() {
        val mine = books()
        buildCatalogue(mine, roots)
        val want = oracle.getJSONArray("order").let { a -> (0 until a.length()).map { a.getString(it) } }
        assertEquals(want.size, mine.size)
        val got = mine.map { it.id }
        if (want != got) {
            val first = want.indices.first { want[it] != got[it] }
            val byId = mine.associateBy { it.id }
            assertTrue(
                "book order differs at $first: want '${byId[want[first]]?.title}' " +
                    "got '${byId[got[first]]?.title}'",
                false,
            )
        }
    }

    @Test
    fun everySortOrderMatchesThePython() {
        val mine = books()
        val catalogue = buildCatalogue(mine, roots)

        val alpha = oracle.getJSONArray("sorted_alpha").let { a -> (0 until a.length()).map { a.getString(it) } }
        assertEquals("A-Z order", alpha, sortSeries(catalogue.rows, SORT_ALPHA).map { it.key })

        val most = oracle.getJSONArray("sorted_most").let { a -> (0 until a.length()).map { a.getString(it) } }
        assertEquals("most-first order", most, sortSeries(catalogue.rows, SORT_MOST).map { it.key })

        val byGenre = sortSeries(catalogue.rows, SORT_GENRE)
        val wantGenre = oracle.getJSONArray("sorted_genre")
        assertEquals("genre order length", wantGenre.length(), byGenre.size)
        val misses = mutableListOf<String>()
        for (i in 0 until wantGenre.length()) {
            val o = wantGenre.getJSONObject(i)
            val row = byGenre[i]
            if (o.getString("key") != row.key) {
                misses += "position $i: want ${o.getString("key")} got ${row.key}"
                continue
            }
            val head = if (o.isNull("head")) null else o.getString("head")
            val subhead = if (o.isNull("subhead")) null else o.getString("subhead")
            if (head != row.head) misses += "${row.key}.head: want $head got ${row.head}"
            if (subhead != row.subhead) misses += "${row.key}.subhead: want $subhead got ${row.subhead}"
        }
        assertTrue(
            "genre ordering differs in ${misses.size} places:\n" + misses.take(20).joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun partitionRoutingMatchesThePython() {
        val mine = books()
        val catalogue = buildCatalogue(mine, roots)
        val report = catalogue.routing
        assertTrue("no routing report", report != null)
        val want = oracle.getJSONObject("routing")

        assertEquals("taught rows", want.getInt("taught"), report!!.taught)
        assertEquals("rows routed", want.getInt("routed"), report.routed)
        assertEquals("rows put back", want.getInt("put_back"), report.putBack)
        assertEquals("rows not put back", want.getInt("not_put_back"), report.notPutBack)
        assertEquals("rows checked", want.getInt("checked"), report.checked)

        val wantNotes = want.getJSONObject("partitions")
        val misses = mutableListOf<String>()
        for (key in wantNotes.keys()) {
            val o = wantNotes.getJSONObject(key)
            val note = report.partitions[key]
            if (note == null) {
                misses += "missing note for $key"
                continue
            }
            if (o.getInt("taught") != note.taught) {
                misses += "$key.taught: want ${o.getInt("taught")} got ${note.taught}"
            }
            if (o.getInt("took") != note.took) {
                misses += "$key.took: want ${o.getInt("took")} got ${note.took}"
            }
            if (o.optInt("put_back", 0) != note.putBack) {
                misses += "$key.put_back: want ${o.optInt("put_back", 0)} got ${note.putBack}"
            }
            // learn.py builds these from a Python set, so their order
            // changes between runs with the hash seed; only membership is
            // reproducible.
            val words = o.getJSONArray("words")
                .let { a -> (0 until a.length()).map { i -> a.getString(i) } }.sorted()
            if (words != note.words.sorted()) {
                misses += "$key.words: want $words got ${note.words.sorted()}"
            }
        }
        assertTrue(
            "partition routing differs in ${misses.size} places:\n" + misses.joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun theTfidfVectoriserMatchesScikitLearnsCharWbAnalyser() {
        // sklearn pads each word with a space; a word shorter than n
        // yields the padded word once and stops.
        assertEquals(listOf(" ab", "ab "), charWbNgrams("ab", 3, 3))
        assertEquals(listOf(" ab "), charWbNgrams("ab", 4, 4))
        assertEquals(listOf(" ab", "abc", "bc "), charWbNgrams("abc", 3, 3))
        val rows = tfidfRows(listOf("abcd", "abcd"))
        assertEquals(0.0, cosineDistance(rows[0], rows[1]), 1e-9)
        val apart = tfidfRows(listOf("aaaa", "zzzz"))
        assertEquals(1.0, cosineDistance(apart[0], apart[1]), 1e-9)
    }

    // The one place the port could not copy the Python: learn.py clusters
    // with scikit-learn. cluster_oracle.json holds the names that reach
    // that stage on the real library, sklearn's own pairwise cosine
    // distance matrix over its TF-IDF, and the clusters it cut. Both are
    // compared here, so a drift in either half is named.
    @Test
    fun theDistanceMatrixMatchesScikitLearnsToNineDecimals() {
        val cluster = JSONObject(resource("cluster_oracle.json"))
        val names = cluster.getJSONArray("rest_names")
            .let { a -> (0 until a.length()).map { i -> a.getString(i) } }
        assertTrue("cluster oracle is empty", names.size > 20)

        val rows = tfidfRows(names)
        val want = cluster.getJSONArray("distances")
        assertEquals(names.size, want.length())
        var worst = 0.0
        var worstAt = ""
        for (i in names.indices) {
            val row = want.getJSONArray(i)
            for (j in names.indices) {
                val diff = kotlin.math.abs(row.getDouble(j) - cosineDistance(rows[i], rows[j]))
                if (diff > worst) {
                    worst = diff
                    worstAt = "${names[i]} vs ${names[j]}"
                }
            }
        }
        assertTrue("biggest distance difference $worst at $worstAt", worst < 1e-9)
    }

    @Test
    fun theClustersMatchScikitLearnsOnTheRealLibrary() {
        val cluster = JSONObject(resource("cluster_oracle.json"))
        val names = cluster.getJSONArray("rest_names")
            .let { a -> (0 until a.length()).map { i -> a.getString(i) } }
        val rows = tfidfRows(names)
        val distance = Array(names.size) { i ->
            DoubleArray(names.size) { j -> cosineDistance(rows[i], rows[j]) }
        }
        val got = averageLinkage(distance, CLUSTER_DISTANCE).map { it.sorted() }.sortedBy { it.first() }
        val wantArr = cluster.getJSONArray("clusters")
        val want = (0 until wantArr.length()).map { i ->
            wantArr.getJSONArray(i).let { a -> (0 until a.length()).map { j -> a.getInt(j) } }
        }.sortedBy { it.first() }
        assertEquals("cluster count", want.size, got.size)
        val misses = mutableListOf<String>()
        for (i in want.indices) {
            if (want[i] != got[i]) {
                misses += "want ${want[i].map { names[it] }} got ${got[i].map { names[it] }}"
            }
        }
        assertTrue(
            "${misses.size} clusters differ from scikit-learn:\n" + misses.joinToString("\n"),
            misses.isEmpty(),
        )
    }

    @Test
    fun averageLinkageMergesOnlyBelowTheThreshold() {
        val d = arrayOf(
            doubleArrayOf(0.0, 0.1, 0.9),
            doubleArrayOf(0.1, 0.0, 0.9),
            doubleArrayOf(0.9, 0.9, 0.0),
        )
        assertEquals(listOf(listOf(0, 1), listOf(2)), averageLinkage(d, 0.62))
        assertEquals(listOf(listOf(0), listOf(1), listOf(2)), averageLinkage(d, 0.05))
        assertEquals(listOf(listOf(0, 1, 2)), averageLinkage(d, 0.95))
    }
